"""
模組名稱：app.db.base
功能說明：ORM 基底類別、約束命名規則、共用欄位 Mixin。
注意事項：
    - 所有 Model 都必須繼承 Base；共用欄位一律透過 Mixin 取得，不要在各 Model 重複定義。
    - NAMING_CONVENTION 決定 PK / FK / 索引 / 約束名稱，須與 app/db/README.md「命名規則」一致。
    - Mixin 欄位以 sort_order 控制位置：id 在最前，時間戳在最後，與 Schema 備註順序一致。
"""

from datetime import datetime
from enum import StrEnum

from sqlalchemy import BigInteger, DateTime, Identity, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# 約束與索引命名規則（Alembic 產生 migration 時也會套用）
NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
}


class Base(DeclarativeBase):
    """所有 ORM Model 的基底類別。"""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdMixin:
    """主鍵欄位：id BIGINT GENERATED BY DEFAULT AS IDENTITY。"""

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True, sort_order=-100)


class TimestampMixin:
    """建立 / 更新時間（TIMESTAMPTZ，以 UTC 儲存）。"""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), sort_order=100
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), sort_order=101
    )


class SoftDeleteMixin:
    """軟刪除時間；NULL 代表未刪除。查詢時必須過濾 deleted_at IS NULL。"""

    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), sort_order=102)


def in_values_check(column: str, enum_cls: type[StrEnum]) -> str:
    """產生 CHECK 條件字串，讓資料庫約束與 Python 列舉保持一致。

    Args:
        column: 欄位名稱。
        enum_cls: 允許值的 StrEnum 類別。

    Returns:
        例如 "status IN ('pending', 'passed')"。
    """
    values = ", ".join(f"'{member.value}'" for member in enum_cls)
    return f"{column} IN ({values})"
